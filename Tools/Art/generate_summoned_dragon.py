"""Build the original Aether Drake sample model using Blender 4.3+.

Run:
  blender --background --python Tools/Art/generate_summoned_dragon.py -- --project-root .

This is an original demonstration creature, not a model of an official card.
The FBX is the runtime asset; the .blend is kept outside Assets deliberately.
"""

import argparse
import json
import math
import sys
from pathlib import Path

import bpy
from mathutils import Vector


def arguments():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    parser = argparse.ArgumentParser()
    parser.add_argument("--project-root", default=str(Path(__file__).resolve().parents[2]))
    parser.add_argument("--preview", default="")
    return parser.parse_args(argv)


def material(name, color, metallic=0.0, roughness=0.45, emission=0.0):
    value = bpy.data.materials.new(name)
    value.diffuse_color = (*color, 1.0)
    value.use_nodes = True
    shader = value.node_tree.nodes.get("Principled BSDF")
    shader.inputs["Base Color"].default_value = (*color, 1.0)
    shader.inputs["Metallic"].default_value = metallic
    shader.inputs["Roughness"].default_value = roughness
    if emission:
        shader.inputs["Emission Color"].default_value = (*color, 1.0)
        shader.inputs["Emission Strength"].default_value = emission
    return value


PARTS = []


def finish_part(obj, name, mat, bone):
    obj.name = name
    if obj.data.materials:
        obj.data.materials.clear()
    obj.data.materials.append(mat)
    bpy.context.view_layer.objects.active = obj
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    group = obj.vertex_groups.new(name=bone)
    group.add(list(range(len(obj.data.vertices))), 1.0, "REPLACE")
    for polygon in obj.data.polygons:
        polygon.use_smooth = False
    PARTS.append(obj)
    return obj


def ellipsoid(name, location, scale, mat, bone, segments=8, rings=4):
    bpy.ops.mesh.primitive_uv_sphere_add(segments=segments, ring_count=rings, location=location)
    obj = bpy.context.object
    obj.scale = scale
    return finish_part(obj, name, mat, bone)


def segment(name, start, end, radius_start, radius_end, mat, bone, vertices=6):
    start = Vector(start)
    end = Vector(end)
    delta = end - start
    bpy.ops.mesh.primitive_cone_add(
        vertices=vertices,
        radius1=radius_start,
        radius2=radius_end,
        depth=delta.length,
        location=(start + end) / 2,
    )
    obj = bpy.context.object
    obj.rotation_euler = delta.to_track_quat("Z", "Y").to_euler()
    bpy.ops.object.transform_apply(location=False, rotation=True, scale=False)
    return finish_part(obj, name, mat, bone)


def custom_mesh(name, verts, faces, mat, bone):
    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(verts, [], faces)
    mesh.update()
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.collection.objects.link(obj)
    return finish_part(obj, name, mat, bone)


def wing(side, skin, bronze, shadow):
    bone = "Wing.L" if side < 0 else "Wing.R"
    shoulder = (side * 0.32, -0.02, 1.24)
    elbow = (side * 0.99, 0.04, 1.80)
    points = [
        elbow,
        (side * 1.98, -0.02, 1.95),
        (side * 1.61, 0.38, 1.56),
        (side * 1.74, 0.79, 1.68),
        (side * 1.07, 0.74, 1.29),
        (side * 1.05, 1.12, 1.33),
        (side * 0.42, 0.64, 1.02),
        shoulder,
    ]
    faces = [(0, index, index + 1) for index in range(1, len(points) - 1)]
    membrane = custom_mesh("WingMembrane" + bone[-2:], points, faces, skin, bone)
    membrane.data.materials.append(shadow)
    for index, polygon in enumerate(membrane.data.polygons):
        polygon.material_index = index % 2
    solid = membrane.modifiers.new("Membrane thickness", "SOLIDIFY")
    solid.thickness = 0.025
    bpy.context.view_layer.objects.active = membrane
    bpy.ops.object.modifier_apply(modifier=solid.name)
    # Ensure vertices generated by Solidify also have the wing weight.
    membrane.vertex_groups[bone].add(list(range(len(membrane.data.vertices))), 1.0, "REPLACE")
    segment("WingUpper" + bone[-2:], shoulder, elbow, 0.095, 0.065, bronze, bone)
    for index in (1, 3, 5, 6):
        segment("WingFinger" + bone[-2:], elbow, points[index], 0.043, 0.012, bronze, bone, 5)
    segment("WingClaw" + bone[-2:], elbow, (side * 1.10, -0.18, 2.03), 0.06, 0, bronze, bone)


def create_geometry(mats):
    red, dark, bronze, gold, cyan, ivory = mats
    ellipsoid("Thorax", (0, 0.0, 0.98), (0.47, 0.70, 0.45), red, "Body", 10, 6)
    ellipsoid("ShoulderArmor", (0, -0.34, 1.18), (0.49, 0.35, 0.34), bronze, "Body")
    ellipsoid("Haunch", (0, 0.48, 0.83), (0.43, 0.35, 0.34), red, "Body")
    # Overlapping ventral plates are visibly different from the angular skin.
    for index in range(5):
        ellipsoid(
            "BellyPlate%02d" % index,
            (0, -0.43 + index * 0.18, 0.79),
            (0.28, 0.16, 0.19),
            gold,
            "Body",
            6,
            3,
        )
    segment("LowerNeck", (0, -0.34, 1.15), (0, -0.73, 1.64), 0.25, 0.19, red, "Neck", 8)
    ellipsoid("NeckArmor", (0, -0.66, 1.49), (0.25, 0.20, 0.25), bronze, "Neck")
    # The pointed snout uses an intentionally original angular silhouette.
    head_verts = [
        (-0.25, -0.70, 1.64), (0.25, -0.70, 1.64),
        (-0.23, -0.79, 1.96), (0.23, -0.79, 1.96),
        (-0.14, -1.28, 1.76), (0.14, -1.28, 1.76),
        (-0.12, -1.31, 1.66), (0.12, -1.31, 1.66),
    ]
    head_faces = [(0, 1, 3, 2), (2, 3, 5, 4), (0, 2, 4, 6), (1, 7, 5, 3), (4, 5, 7, 6), (0, 6, 7, 1)]
    custom_mesh("HornedHead", head_verts, head_faces, red, "Head")
    ellipsoid("Jaw", (0, -1.02, 1.59), (0.175, 0.29, 0.075), bronze, "Jaw", 8, 3)
    for side in (-1, 1):
        # Eye gems are separate geometry and remain readable at card-table scale.
        ellipsoid("EyeGem", (side * 0.222, -0.91, 1.815), (0.039, 0.089, 0.042), cyan, "Head", 6, 3)
        segment("Brow", (side * 0.22, -1.01, 1.866), (side * 0.28, -0.76, 1.91), 0.045, 0.068, bronze, "Head")
        segment("CrownHorn", (side * 0.16, -0.73, 1.92), (side * 0.31, -0.48, 2.19), 0.082, 0, gold, "Head")
        segment("CheekHorn", (side * 0.19, -0.75, 1.69), (side * 0.36, -0.49, 1.69), 0.063, 0, bronze, "Head")
        for tooth_index in range(3):
            y = -1.20 + tooth_index * 0.12
            segment("UpperFang", (side * 0.135, y, 1.68), (side * 0.12, y - 0.02, 1.585), 0.025, 0, ivory, "Head", 5)
    for side in (-1, 1):
        for is_front in (True, False):
            suffix = ("Fore" if is_front else "Hind") + (".L" if side < 0 else ".R")
            y = -0.39 if is_front else 0.46
            hip = (side * 0.32, y, 0.89)
            knee = (side * 0.54, y + (0.02 if is_front else 0.17), 0.45)
            ankle = (side * 0.47, y - 0.10, 0.12)
            segment("Upper" + suffix, hip, knee, 0.15 if is_front else 0.19, 0.12, red, suffix)
            ellipsoid("Knee" + suffix, knee, (0.15, 0.14, 0.14), bronze, suffix)
            segment("Lower" + suffix, knee, ankle, 0.115, 0.085, bronze, suffix)
            ellipsoid("Foot" + suffix, (side * 0.47, y - 0.19, 0.09), (0.16, 0.23, 0.075), red, suffix)
            for toe in (-1, 0, 1):
                x = side * 0.47 + toe * 0.09
                segment("Claw" + suffix, (x, y - 0.31, 0.09), (x, y - 0.44, 0.045), 0.042, 0, gold, suffix, 5)
    segment("TailBase", (0, 0.47, 0.93), (0, 1.18, 0.91), 0.22, 0.11, red, "Tail")
    segment("TailTip", (0, 1.18, 0.91), (0.08, 1.81, 1.18), 0.11, 0.025, red, "TailTip")
    segment("TailSpear", (0.08, 1.63, 1.10), (0.12, 2.01, 1.40), 0.13, 0, bronze, "TailTip", 4)
    for index, (y, z, size) in enumerate([(-0.32, 1.50, 0.20), (-0.03, 1.45, 0.23), (0.25, 1.36, 0.20), (0.55, 1.16, 0.16), (0.92, 1.04, 0.13), (1.29, 1.05, 0.11)]):
        bone = "Body" if index < 4 else ("Tail" if index == 4 else "TailTip")
        segment("DorsalSpike%02d" % index, (0, y, z - 0.04), (0, y + 0.10, z + size), size * 0.4, 0, gold, bone, 4)
    wing(-1, red, bronze, dark)
    wing(1, red, bronze, dark)


BONES = {
    "Root": ((0, 0, 0), (0, 0, 0.25), None),
    "Body": ((0, 0.35, 0.95), (0, -0.36, 1.15), "Root"),
    "Neck": ((0, -0.36, 1.15), (0, -0.73, 1.64), "Body"),
    "Head": ((0, -0.73, 1.64), (0, -1.22, 1.76), "Neck"),
    "Jaw": ((0, -0.74, 1.63), (0, -1.25, 1.59), "Head"),
    "Wing.L": ((-0.32, -0.02, 1.24), (-1.40, 0.1, 1.85), "Body"),
    "Wing.R": ((0.32, -0.02, 1.24), (1.40, 0.1, 1.85), "Body"),
    "Fore.L": ((-0.32, -0.39, 0.89), (-0.47, -0.49, 0.12), "Body"),
    "Fore.R": ((0.32, -0.39, 0.89), (0.47, -0.49, 0.12), "Body"),
    "Hind.L": ((-0.32, 0.46, 0.89), (-0.47, 0.36, 0.12), "Body"),
    "Hind.R": ((0.32, 0.46, 0.89), (0.47, 0.36, 0.12), "Body"),
    "Tail": ((0, 0.47, 0.93), (0, 1.18, 0.91), "Body"),
    "TailTip": ((0, 1.18, 0.91), (0.08, 1.81, 1.18), "Tail"),
}


def create_rig():
    bpy.ops.object.select_all(action="DESELECT")
    bpy.ops.object.armature_add(enter_editmode=True)
    rig = bpy.context.object
    rig.name = "AetherDrakeRig"
    rig.data.name = "AetherDrakeSkeleton"
    for bone in list(rig.data.edit_bones):
        rig.data.edit_bones.remove(bone)
    for name, (head, tail, parent) in BONES.items():
        bone = rig.data.edit_bones.new(name)
        bone.head, bone.tail = head, tail
        if parent:
            bone.parent = rig.data.edit_bones[parent]
        bone.use_deform = True
    bpy.ops.object.mode_set(mode="OBJECT")
    bpy.ops.object.select_all(action="DESELECT")
    for part in PARTS:
        part.select_set(True)
    bpy.context.view_layer.objects.active = PARTS[0]
    bpy.ops.object.join()
    mesh = bpy.context.object
    mesh.name = "AetherDrakeMesh"
    bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
    mesh.parent = rig
    armature = mesh.modifiers.new("Aether Drake skeleton", "ARMATURE")
    armature.object = rig
    rig.show_in_front = True
    for bone in rig.pose.bones:
        bone.rotation_mode = "XYZ"
    return rig, mesh


def neutral_pose(rig):
    for bone in rig.pose.bones:
        bone.location = (0, 0, 0)
        bone.rotation_euler = (0, 0, 0)
        bone.scale = (1, 1, 1)


def key_pose(rig, frame):
    for bone in rig.pose.bones:
        bone.keyframe_insert(data_path="location", frame=frame, group=bone.name)
        bone.keyframe_insert(data_path="rotation_euler", frame=frame, group=bone.name)
        bone.keyframe_insert(data_path="scale", frame=frame, group=bone.name)


def create_actions(rig):
    rig.animation_data_create()
    actions = []
    for name, frames in [("Idle", [1, 13, 25, 37, 49]), ("Summon", [1, 10, 22, 34, 48]), ("Attack", [1, 9, 16, 23, 36])]:
        action = bpy.data.actions.new(name)
        action.use_fake_user = True
        rig.animation_data.action = action
        for index, frame in enumerate(frames):
            neutral_pose(rig)
            pose = rig.pose.bones
            if name == "Idle":
                pulse = math.sin((frame - 1) / 48 * math.tau)
                pose["Body"].scale = (1 + pulse * 0.012, 1 + pulse * 0.018, 1 + pulse * 0.012)
                pose["Neck"].rotation_euler.x = pulse * 0.026
                pose["Head"].rotation_euler.z = pulse * 0.02
                pose["Wing.L"].rotation_euler.x = pulse * 0.07
                pose["Wing.R"].rotation_euler.x = -pulse * 0.07
                pose["Tail"].rotation_euler.z = pulse * 0.07
                pose["TailTip"].rotation_euler.z = -pulse * 0.1
            elif name == "Summon":
                scales = [0.015, 0.55, 1.09, 0.97, 1.0]
                heights = [-0.1, 0.4, 0.22, -0.03, 0.0]
                flap = [0.8, -0.35, 0.55, -0.1, 0.0][index]
                pose["Root"].scale = (scales[index],) * 3
                # The Root bone localY points upwards in this rest pose.
                pose["Root"].location.y = heights[index]
                pose["Wing.L"].rotation_euler.x = flap
                pose["Wing.R"].rotation_euler.x = -flap
                pose["Head"].rotation_euler.x = [-0.2, -0.3, 0.15, -0.05, 0][index]
                pose["Jaw"].rotation_euler.x = [0.1, 0.12, 0.33, 0.1, 0][index]
            else:
                lunge = [0, 0.10, -0.65, -0.45, 0][index]
                # Root localZ maps to -worldY, i.e. the creature's forward axis.
                pose["Root"].location.z = -lunge
                pose["Root"].location.y = [0, 0.04, 0.19, 0.10, 0][index]
                pose["Body"].rotation_euler.x = [0, -0.12, 0.18, 0.06, 0][index]
                pose["Neck"].rotation_euler.x = [0, -0.2, 0.26, 0.1, 0][index]
                pose["Jaw"].rotation_euler.x = [0, 0.12, 0.43, 0.21, 0][index]
                pose["Fore.L"].rotation_euler.x = [0, -0.3, 0.3, 0.15, 0][index]
                pose["Fore.R"].rotation_euler.x = [0, -0.22, 0.22, 0.10, 0][index]
                wing_angle = [0, 0.18, 0.43, 0.15, 0][index]
                pose["Wing.L"].rotation_euler.x = wing_angle
                pose["Wing.R"].rotation_euler.x = -wing_angle
            key_pose(rig, frame)
        for curve in action.fcurves:
            for key in curve.keyframe_points:
                key.interpolation = "BEZIER"
            if name == "Idle":
                curve.modifiers.new("CYCLES")
        action["loop"] = name == "Idle"
        actions.append(action)
    rig.animation_data.action = actions[0]
    neutral_pose(rig)
    bpy.context.scene.frame_set(1)
    return actions


def add_preview_scene():
    ground_mat = material("Preview ground", (0.035, 0.05, 0.07), 0.1, 0.55)
    bpy.ops.mesh.primitive_plane_add(size=200, location=(0, 0, -0.015))
    ground = bpy.context.object
    ground.name = "PREVIEW_ONLY_Ground"
    ground.data.materials.append(ground_mat)
    bpy.ops.object.camera_add(location=(4.1, -5.8, 3.25))
    camera = bpy.context.object
    camera.name = "PREVIEW_ONLY_Camera"
    camera.rotation_euler = (Vector((0, 0.12, 1.05)) - camera.location).to_track_quat("-Z", "Y").to_euler()
    camera.data.type = "ORTHO"
    camera.data.ortho_scale = 5.25
    bpy.context.scene.camera = camera
    for name, location, energy, color, size in [
        ("Key", (1, -3, 5), 850, (0.9, 0.94, 1), 4),
        ("Fill", (-4, -1, 2.2), 600, (0.25, 0.56, 1), 3),
        ("Rim", (0, 3.5, 4), 1100, (1, 0.42, 0.16), 3),
    ]:
        bpy.ops.object.light_add(type="AREA", location=location)
        light = bpy.context.object
        light.name = "PREVIEW_ONLY_" + name
        light.data.energy, light.data.color, light.data.shape, light.data.size = energy, color, "DISK", size
        light.rotation_euler = (Vector((0, 0, 1)) - light.location).to_track_quat("-Z", "Y").to_euler()
    scene = bpy.context.scene
    scene.world.color = (0.08, 0.08, 0.08)
    scene.render.engine = "CYCLES"
    scene.cycles.device = "CPU"
    scene.cycles.samples = 32
    scene.cycles.use_denoising = False
    for layer in scene.view_layers:
        layer.cycles.use_denoising = False
    scene.render.resolution_x = 1000
    scene.render.resolution_y = 800
    scene.render.resolution_percentage = 100
    scene.view_settings.view_transform = "AgX"


def main():
    args = arguments()
    root = Path(args.project_root).resolve()
    output = root / "Assets/BattleSpirits/Resources/Models"
    source = root / "Tools/Art"
    output.mkdir(parents=True, exist_ok=True)
    source.mkdir(parents=True, exist_ok=True)
    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.object.delete(use_global=False)
    for action in list(bpy.data.actions):
        bpy.data.actions.remove(action)
    bpy.context.scene.render.fps = 24
    mats = [
        material("Drake crimson scales", (0.38, 0.045, 0.065), 0.2, 0.38),
        material("Drake wine membrane", (0.14, 0.018, 0.04), 0.1, 0.55),
        material("Drake burnished bronze", (0.48, 0.22, 0.075), 0.6, 0.32),
        material("Drake antique gold", (0.83, 0.57, 0.19), 0.6, 0.35),
        material("Drake aether eyes", (0.025, 0.8, 1.0), 0.2, 0.2, 2.5),
        material("Drake ivory fangs", (0.88, 0.8, 0.58), 0.05, 0.4),
    ]
    create_geometry(mats)
    rig, mesh = create_rig()
    actions = create_actions(rig)
    bpy.context.scene.frame_start, bpy.context.scene.frame_end = 1, 49
    bpy.ops.object.select_all(action="DESELECT")
    rig.select_set(True)
    mesh.select_set(True)
    bpy.context.view_layer.objects.active = rig
    fbx = output / "SummonedDragon.fbx"
    bpy.ops.export_scene.fbx(
        filepath=str(fbx),
        use_selection=True,
        object_types={"ARMATURE", "MESH"},
        apply_unit_scale=True,
        apply_scale_options="FBX_SCALE_UNITS",
        axis_forward="-Z",
        axis_up="Y",
        add_leaf_bones=False,
        use_armature_deform_only=True,
        bake_anim=True,
        bake_anim_use_all_bones=True,
        bake_anim_use_all_actions=True,
        bake_anim_use_nla_strips=False,
        bake_anim_force_startend_keying=True,
        bake_anim_simplify_factor=0.0,
        path_mode="AUTO",
        embed_textures=False,
    )
    add_preview_scene()
    rig.animation_data.action = bpy.data.actions["Idle"]
    bpy.context.scene.frame_set(1)
    blend = source / "SummonedDragon.blend"
    bpy.ops.wm.save_as_mainfile(filepath=str(blend))
    report = {
        "model": "Aether Drake — original demonstration model",
        "blender_version": bpy.app.version_string,
        "fbx": str(fbx),
        "blend": str(blend),
        "vertex_count": len(mesh.data.vertices),
        "polygon_count": len(mesh.data.polygons),
        "triangles": sum(len(face.vertices) - 2 for face in mesh.data.polygons),
        "bones": len(rig.data.bones),
        "actions": [{"name": action.name, "frame_range": list(action.frame_range), "fps": 24} for action in actions],
        "rig_type": "Generic",
        "textures": "None; six mesh materials",
        "fbx_bytes": fbx.stat().st_size,
        "unity_import_tested": False,
    }
    report_path = root.parent / "battle-spirits-work/model-build-report.json"
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(json.dumps(report, indent=2) + "\n")
    print("MODEL_BUILD_REPORT " + json.dumps(report))
    if args.preview:
        bpy.context.scene.render.filepath = str(Path(args.preview).resolve())
        bpy.ops.render.render(write_still=True)


if __name__ == "__main__":
    main()
